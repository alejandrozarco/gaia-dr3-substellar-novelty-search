"""test_rehunt.py — regression + dry-run for the DR4 rehunt harness.

Runs fully offline. The headline test is a *closed-loop regression*: feed the
committed DR3 v2 roster's own input columns back through the harness (adapter ->
rehunt -> derive_row_v2) and assert it reproduces today's tier roster exactly.
That pins the harness as a faithful wrapper of the production cascade
(``scripts/streaming/v2_corrected/consumer_v2.py``) — if anyone forks/reimplements
the science here, this test breaks.

Run::

    ~/claude_projects/ostinato/.venv/bin/python -m pytest \
        scripts/dr4_pipeline/rehunt/test_rehunt.py -q

or as a plain script (``python test_rehunt.py``) for a one-shot dry-run summary.

KEY FINDING baked into these tests (see also the module docstring of diff.py and
the RESEARCH_LOG block returned by the build task):

  * The committed ``data/derived/main_hunt_derived_v2.parquet`` was generated by
    an EARLIER code path that fixed M_1 = 1.5 (its ``M1_msun_v2`` column is
    uniformly 1.5) — it PRE-DATES the current ``consumer_v2.select_m1`` FLAME
    preference. So a faithful re-run reproduces it ONLY when M_1 is forced to the
    same fixed 1.5 (no FLAME leak). With FLAME masses fed in, ~half the pool
    legitimately re-tiers (the documented M_1 correction) — that is NOT a harness
    bug, it is the committed parquet being stale w.r.t. current code.
  * The raw producer chunks (``data/raw_chunks/main_RA*.parquet``) do NOT carry
    the NSS ``flags`` column (F#33 was added 2026-05-31, after they were made),
    so F#33 no-ops on them. ``flags`` exists offline only inside the committed
    v2 parquet itself.
"""
from __future__ import annotations
