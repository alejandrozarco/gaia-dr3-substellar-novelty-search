def _dry_run():
    if not COMMITTED_V2.exists():
        print("committed v2 parquet absent; cannot dry-run")
        return
    print("=== DR3 dry-run (self-loop on committed v2 inputs, M_1=1.5 fixed) ===")
    df, adapted = A.load_nss_table(COMMITTED_V2, profile=_PROFILE_BASELINE)
    out = RH.run_cascade(adapted, m1_prior=1.5)
    base = _load_committed()[["source_id", "tier_v2", "M2_msun_v2", "P_d"]]
    d = D.diff_rosters(base, out)
    print(D.render_report(d, "committed main_hunt_derived_v2",
                          "rehunt self-loop (M1=1.5)"))


if __name__ == "__main__":
    _dry_run()
