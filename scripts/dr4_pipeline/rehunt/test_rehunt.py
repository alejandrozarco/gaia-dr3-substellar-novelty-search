def test_adapter_computes_a_phot_from_thiele_innes():
    """When no a_phot column is mapped, the adapter derives it from A,B,F,G via
    the production photocentric_a_mas (DR3-raw profile path)."""
    A_, B_, F_, G_ = -0.6366, -0.2300, 0.0960, -0.8180
    expect = c2.photocentric_a_mas(A_, B_, F_, G_)
    row = pd.Series({
        "source_id": 413546904690928000,
        "a_thiele_innes": A_, "b_thiele_innes": B_,
        "f_thiele_innes": F_, "g_thiele_innes": G_,
        "period": 751.3, "eccentricity": 0.07, "parallax": 2.07,
        "nss_solution_type": "AstroSpectroSB1",
    })
    out = A.adapt_row(row, A.DR3_RAW)
    assert out["a_phot_mas"] == pytest.approx(expect, rel=1e-9)
    assert out["source_id"] == 413546904690928000  # exact 18/19-digit int
    assert out["in_sb2"] is False                   # default applied


def test_adapter_first_present_fallback_and_rename():
    """dr3_derived maps period<-[P_d,period]; pick P_d, and logg<-[...,logg]."""
    row = pd.Series({
        "source_id": 1, "a_phot_mas": 1.0, "P_d": 500.0, "e": 0.1,
        "parallax": 2.0, "nss_parallax": 3.0, "logg": 2.5,
        "nss_solution_type": "Orbital",
    })
    out = A.adapt_row(row, A.DR3_DERIVED)
    assert out["period"] == 500.0
    assert out["eccentricity"] == 0.1
    assert out["logg_gspphot"] == 2.5     # mapped from `logg`
    assert out["nss_parallax"] == 3.0


