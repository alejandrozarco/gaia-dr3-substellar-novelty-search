def _frame(rows):
    return pd.DataFrame(rows)


def test_diff_classifies_new_vanished_promoted_demoted():
    base = _frame([
        {"source_id": 1, "tier_v2": "Tier-1 NS", "M2_msun_v2": 1.5, "P_d": 500},
        {"source_id": 2, "tier_v2": "Tier-2 (RV inconclusive — needs follow-up)",
         "M2_msun_v2": 1.3, "P_d": 600},
        {"source_id": 3, "tier_v2": "Tier-1 BH", "M2_msun_v2": 9.0, "P_d": 1200},
        {"source_id": 4, "tier_v2": "Characterized — M-dwarf companion (0.08 ≤ M_2 < 0.5)",
         "M2_msun_v2": 0.3, "P_d": 400},
    ])
    new = _frame([
        # 1 demoted, 2 promoted to Tier-1, 3 vanished (ERROR), 5 new Tier-1
        {"source_id": 1, "tier_v2": "Demoted (failed F#30 K-giant chromatic)",
         "M2_msun_v2": 1.5, "P_d": 500},
        {"source_id": 2, "tier_v2": "Tier-1 NS", "M2_msun_v2": 1.4, "P_d": 600},
        {"source_id": 3, "tier_v2": "ERROR", "M2_msun_v2": None, "P_d": None},
        {"source_id": 4, "tier_v2": "Characterized — M-dwarf companion (0.08 ≤ M_2 < 0.5)",
         "M2_msun_v2": 0.3, "P_d": 400},
        {"source_id": 5, "tier_v2": "Tier-1 NS", "M2_msun_v2": 1.6, "P_d": 700},
    ])
    d = D.diff_rosters(base, new).set_index("source_id")
    assert d.at[1, "change"] == "DEMOTED"
    assert d.at[2, "change"] == "PROMOTED"
    assert d.at[3, "change"] == "VANISHED"
    assert d.at[4, "change"] == "SAME"
    assert d.at[5, "change"] == "NEW"


def test_diff_flags_mass_mover():
    base = _frame([{"source_id": 1, "tier_v2": "Tier-1 NS", "M2_msun_v2": 1.30, "P_d": 500}])
    new = _frame([{"source_id": 1, "tier_v2": "Tier-1 NS", "M2_msun_v2": 1.50, "P_d": 500}])
    d = D.diff_rosters(base, new, mass_thresh=0.05).set_index("source_id")
    assert d.at[1, "change"] == "MASS_MOVER"
    assert d.at[1, "dM2"] == pytest.approx(0.20)


def test_diff_tier_rank_substring_fallback():
    # Unknown exact label but recognizable prefix still ranks as Tier-1.
    assert D.tier_rank("Tier-1 NS (DR4 refit)") == 90
    assert D.tier_rank("Tier-1 BH something") == 100
    assert D.tier_rank("Demoted (new reason)") == 10
    assert D.tier_rank(None) == -1


