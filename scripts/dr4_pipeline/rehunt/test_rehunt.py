import pytest

HERE = Path(__file__).resolve().parent
ROOT = Path(os.path.expanduser("~/claude_projects/gaia-recovered-2026-05-27"))
COMMITTED_V2 = ROOT / "data" / "derived" / "main_hunt_derived_v2.parquet"

for p in (str(HERE), str(HERE.parents[1] / "streaming" / "v2_corrected")):
    if p not in sys.path:
        sys.path.insert(0, p)

import adapter as A          # noqa: E402
import rehunt as RH          # noqa: E402
import diff as D             # noqa: E402
import consumer_v2 as c2     # noqa: E402


# A profile that mirrors the committed parquet's input schema but forces the
# M_1 = 1.5 path the baseline was generated with (no FLAME leak from M1_msun).
_PROFILE_BASELINE = A.Profile(
    name="dr3_derived_fixedM1",
    mapping={**A.DR3_DERIVED.mapping,
             "mass_flame": ["__absent__"],
             "mass_flame_spec": ["__absent__"]},
)


def _load_committed() -> pd.DataFrame:
    import polars as pl
    return pl.read_parquet(COMMITTED_V2).to_pandas()


# ---------------------------------------------------------------------------
# 1) Closed-loop regression — the headline dry-run
# ---------------------------------------------------------------------------

@pytest.mark.skipif(not COMMITTED_V2.exists(), reason="committed v2 parquet absent")
def test_reproduces_committed_roster_exactly():
    """Feed the committed v2 inputs through the harness (M_1=1.5 fixed path) and
    require an EXACT reproduction of the committed tier_v2 + M2 columns."""
    df, adapted = A.load_nss_table(COMMITTED_V2, profile=_PROFILE_BASELINE)
    out = RH.run_cascade(adapted, m1_prior=1.5).set_index("source_id")
    base = _load_committed().set_index("source_id")
    common = base.index.intersection(out.index)
    assert len(common) == len(base) == len(out), "row-count drift"

    tier_mismatch = int(
        (base.loc[common, "tier_v2"].values != out.loc[common, "tier_v2"].values).sum()
    )
    assert tier_mismatch == 0, f"{tier_mismatch} tier mismatches vs committed roster"

    dM2 = (base.loc[common, "M2_msun_v2"] - out.loc[common, "M2_msun_v2"]).abs()
    assert np.nanmax(dM2) < 1e-9, f"M2 drift max={np.nanmax(dM2):.3e}"


@pytest.mark.skipif(not COMMITTED_V2.exists(), reason="committed v2 parquet absent")
def test_diff_against_committed_is_clean_via_self_loop():
    """diff.py on (committed baseline vs harness self-loop) must report no tier
    movement (NEW/PROMOTED/DEMOTED/VANISHED all empty)."""
    df, adapted = A.load_nss_table(COMMITTED_V2, profile=_PROFILE_BASELINE)
    out = RH.run_cascade(adapted, m1_prior=1.5)
    base = _load_committed()[["source_id", "tier_v2", "M2_msun_v2", "P_d"]]
    d = D.diff_rosters(base, out)
    moved = d["change"].isin(["NEW", "PROMOTED", "DEMOTED", "VANISHED"])
    assert moved.sum() == 0, (
        f"{int(moved.sum())} sources moved tiers in self-loop: "
        f"{d.loc[moved, 'change'].value_counts().to_dict()}"
    )


@pytest.mark.skipif(not COMMITTED_V2.exists(), reason="committed v2 parquet absent")
def test_committed_tier1_count_pinned():
    """Pin today's Tier-1 NS+BH roster size (199) so a drift is loud."""
    base = _load_committed()
    n_t1 = int(base["tier_v2"].isin(["Tier-1 NS", "Tier-1 BH"]).sum())
    assert n_t1 == 199, f"committed Tier-1 roster changed: {n_t1} (was 199)"


# ---------------------------------------------------------------------------
# 2) Harness == direct derive_row_v2 (no science fork) — invariant on a slice
# ---------------------------------------------------------------------------

@pytest.mark.skipif(not COMMITTED_V2.exists(), reason="committed v2 parquet absent")
def test_harness_equals_direct_derive_on_slice():
    """run_cascade(adapt(row)) must equal derive_row_v2(adapt(row)) row-by-row."""
    df, adapted = A.load_nss_table(COMMITTED_V2, profile=_PROFILE_BASELINE, limit=500)
    out = RH.run_cascade(adapted, m1_prior=1.5).set_index("source_id")
    for row in adapted:
        direct = c2.derive_row_v2(row, M1_prior=1.5)
        sid = row["source_id"]
        if "error" in direct:
            assert out.at[sid, "tier_v2"] == "ERROR"
            continue
        assert out.at[sid, "tier_v2"] == direct["tier_v2"]
        assert abs(out.at[sid, "M2_msun_v2"] - direct["M2_msun_v2"]) < 1e-12


